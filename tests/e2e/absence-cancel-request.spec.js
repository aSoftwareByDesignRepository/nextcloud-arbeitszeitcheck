/**
 * FA-2b/FA-2c cancel + cancel-request E2E —
 * spec: planning/features/arbeitszeitcheck/absence-storno-conversion-bt-rules-2026-11
 *
 * API-level roundtrips through browser contexts (robust against markup):
 * - owner request → flags set, status stays approved (NN-12)
 * - duplicate request → 409 cancel_request_pending
 * - withdraw → flags cleared
 * - manager decline → flags cleared, approved
 * - manager approve → shared cancel pipeline → cancelled
 * - manager direct cancel → reason_required / already_ended / revision_stale
 *
 * Owner = SUBSTITUTE like absence-vacation-to-sick.spec.js — the shared
 * e2e_employee calendar is residue-saturated for running vacations.
 */
import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { login, credsFromEnv } from './helpers/auth.js'
import { api, apiAllowFailure } from './helpers/api.js'

const APP = '/apps/arbeitszeitcheck'

function ymd(offsetDays) {
	const d = new Date()
	d.setDate(d.getDate() + offsetDays)
	return d.toISOString().slice(0, 10)
}

/**
 * Server-side "today" — the dev instance clock can lag the host by days
 * (observed 2026-11: DB CURDATE() ≠ host Date). The HTTP Date header is
 * generated by the server, so every seed/reuse decision keys off it.
 */
async function serverToday(page) {
	const res = await page.request.fetch(`${APP}/api/absences`, { method: 'GET' })
	const date = res.headers()['date']
	if (!date) {
		throw new Error('server response carries no Date header')
	}
	return new Date(date).toISOString().slice(0, 10)
}

function shift(baseYmd, days) {
	const d = new Date(baseYmd + 'T12:00:00Z')
	d.setUTCDate(d.getUTCDate() + days)
	return d.toISOString().slice(0, 10)
}

function ownerRole() {
	return process.env.NC_SUBSTITUTE_USER ? 'SUBSTITUTE' : 'EMPLOYEE'
}

/**
 * Find an existing running approved vacation without an open cancel
 * request, or seed one spanning the SERVER's today (isCurrent is
 * server-computed — immune to host/instance clock drift).
 */
async function runningVacation(mgr, userId) {
	// The list endpoint caps ranges at 365 days — center on server today.
	const today = await serverToday(mgr)
	const list = await apiAllowFailure(mgr, 'GET',
		`${APP}/api/manager/employee-absences?employeeId=${userId}&startDate=${shift(today, -150)}&endDate=${shift(today, 150)}&limit=300`)
	const rows = list.json?.entries ?? []
	const reuse = rows.find(
		(a) => a.type === 'vacation' && a.status === 'approved' && !a.cancelRequested
			&& a.startDate <= today && a.endDate >= today,
	)
	if (reuse) {
		return reuse
	}
	// Seed fallback: only possible when today itself is free (any approved
	// row covering today blocks the whole range). Probe the end forward.
	for (let span = 5; span <= 90; span += 5) {
		const res = await apiAllowFailure(mgr, 'POST', `${APP}/api/manager/employee-absences`, {
			data: {
				userId,
				type: 'vacation',
				startDate: shift(today, -1),
				endDate: shift(today, span),
				reason: 'e2e cancel-request seed',
			},
		})
		if (res.ok && res.json?.absence) {
			return res.json.absence
		}
	}
	throw new Error('no running approved vacation available (reuse + seed exhausted)')
}

/** Seed an approved vacation fully in the past (already_ended probing). */
async function seedEndedVacation(page, userId) {
	const today = await serverToday(page)
	for (let back = 0; back < 400; back += 7) {
		const res = await apiAllowFailure(page, 'POST', `${APP}/api/manager/employee-absences`, {
			data: {
				userId,
				type: 'vacation',
				startDate: shift(today, -20 - back),
				endDate: shift(today, -15 - back),
				reason: 'e2e manager-cancel seed',
			},
		})
		if (res.ok && res.json?.absence) {
			return res.json.absence
		}
	}
	throw new Error('no free ended vacation seed window found')
}

/** Fresh owner-side view of a single absence (updatedAt + flags). */
async function ownerAbsence(emp, id) {
	const today = await serverToday(emp)
	const res = await apiAllowFailure(emp, 'GET', `${APP}/api/absences?start_date=${shift(today, -150)}&end_date=${shift(today, 150)}&limit=300`)
	return (res.json?.absences ?? []).find((a) => a.id === id) ?? null
}

/** Fresh manager-side row (updatedAt for CAS). */
async function managerRow(mgr, userId, id) {
	const today = await serverToday(mgr)
	const res = await apiAllowFailure(mgr, 'GET',
		`${APP}/api/manager/employee-absences?employeeId=${userId}&startDate=${shift(today, -150)}&endDate=${shift(today, 150)}&limit=300`)
	return (res.json?.entries ?? []).find((a) => a.id === id) ?? null
}

test.describe('Absence cancel request + manager cancel', () => {
	test.skip(
		!process.env.NC_MANAGER_USER || (!process.env.NC_SUBSTITUTE_USER && !process.env.NC_EMPLOYEE_USER),
		'Requires NC_MANAGER_USER/NC_MANAGER_PASS + NC_SUBSTITUTE_USER or NC_EMPLOYEE_USER creds',
	)

	test('owner request → approve roundtrip: flags set, approved until decision, CAS everywhere', async ({ browser }) => {
		const role = ownerRole()
		const ownerId = process.env[`NC_${role}_USER`]
		const mgr = await browser.newPage()
		const emp = await browser.newPage()

		await login(mgr, credsFromEnv('MANAGER'))
		await mgr.goto(APP + '/manager')
		const vacation = await runningVacation(mgr, ownerId)
		expect(vacation.status).toBe('approved')

		await login(emp, credsFromEnv(role))
		await emp.goto(APP + '/absences')
		const fresh = await ownerAbsence(emp, vacation.id)
		expect(fresh).toBeTruthy()
		expect(fresh.canRequestCancel).toBe(true)

		// Request — flags set, status stays approved.
		const req = await api(emp, 'POST', `${APP}/api/absences/${vacation.id}/cancel-request`, {
			data: { expectedUpdatedAt: fresh.updatedAt, reason: 'Trip fell through' },
		})
		expect(req.absence.status).toBe('approved')
		expect(req.absence.cancelRequested).toBe(true)
		expect(req.absence.cancelRequestReason).toBe('Trip fell through')

		// Duplicate → 409 cancel_request_pending (no double request).
		const dup = await apiAllowFailure(emp, 'POST', `${APP}/api/absences/${vacation.id}/cancel-request`, {
			data: { expectedUpdatedAt: req.absence.updatedAt, reason: 'again' },
		})
		expect(dup.status).toBe(409)
		expect(dup.json.error_code).toBe('cancel_request_pending')

		// Stale CAS on manager approve → 409 revision_stale.
		const stale = await apiAllowFailure(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${vacation.id}/cancel-request/approve`, {
				data: { expectedUpdatedAt: fresh.updatedAt },
			})
		expect(stale.status).toBe(409)
		expect(stale.json.error_code).toBe('revision_stale')

		// The dashboard pending-approvals card must surface the open
		// request with decide actions (not drop it as unknown type).
		await mgr.goto(APP + '/manager')
		const card = mgr.locator('.pending-approval-card', { has: mgr.locator(`.btn-approve-cancel-request[data-absence-id="${vacation.id}"]`) })
		await expect(card).toBeVisible()
		await expect(card.locator('.azc-status-chip[data-status="cancel_requested"]')).toBeVisible()
		await expect(card.locator('.btn-decline-cancel-request')).toBeVisible()

		// Fresh approve → shared pipeline: cancelled + flags cleared.
		const row = await managerRow(mgr, ownerId, vacation.id)
		expect(row.cancelRequested).toBe(true)
		expect(row.canDecideCancelRequest).toBe(true)
		const ok = await api(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${vacation.id}/cancel-request/approve`, {
				data: { expectedUpdatedAt: row.updatedAt },
			})
		expect(ok.absence.status).toBe('cancelled')
		expect(ok.absence.cancelRequested).toBe(false)
	})

	test('owner withdraw clears flags without touching the status', async ({ browser }) => {
		const role = ownerRole()
		const ownerId = process.env[`NC_${role}_USER`]
		const mgr = await browser.newPage()
		const emp = await browser.newPage()

		await login(mgr, credsFromEnv('MANAGER'))
		await mgr.goto(APP + '/manager')
		const vacation = await runningVacation(mgr, ownerId)

		await login(emp, credsFromEnv(role))
		await emp.goto(APP + '/absences')
		const fresh = await ownerAbsence(emp, vacation.id)

		await api(emp, 'POST', `${APP}/api/absences/${vacation.id}/cancel-request`, {
			data: { expectedUpdatedAt: fresh.updatedAt, reason: 'withdraw me' },
		})
		const pending = await ownerAbsence(emp, vacation.id)
		expect(pending.cancelRequested).toBe(true)

		const wd = await api(emp, 'POST', `${APP}/api/absences/${vacation.id}/cancel-request/withdraw`, {
			data: { expectedUpdatedAt: pending.updatedAt },
		})
		expect(wd.absence.status).toBe('approved')
		expect(wd.absence.cancelRequested).toBe(false)
		expect(wd.absence.cancelRequestReason).toBeNull()
	})

	test('open cancel-request card passes an axe scan (WCAG)', async ({ browser }) => {
		const role = ownerRole()
		const ownerId = process.env[`NC_${role}_USER`]
		// AxeBuilder requires a page from an explicit browser context.
		const mgrCtx = await browser.newContext()
		const empCtx = await browser.newContext()
		const mgr = await mgrCtx.newPage()
		const emp = await empCtx.newPage()

		await login(mgr, credsFromEnv('MANAGER'))
		await mgr.goto(APP + '/manager')
		const vacation = await runningVacation(mgr, ownerId)

		await login(emp, credsFromEnv(role))
		await emp.goto(APP + '/absences')
		const fresh = await ownerAbsence(emp, vacation.id)
		await api(emp, 'POST', `${APP}/api/absences/${vacation.id}/cancel-request`, {
			data: { expectedUpdatedAt: fresh.updatedAt, reason: 'a11y scan' },
		})

		await mgr.goto(APP + '/manager')
		await mgr.locator(`.btn-approve-cancel-request[data-absence-id="${vacation.id}"]`).waitFor()
		const results = await new AxeBuilder({ page: mgr })
			.include('.pending-approval-card')
			.analyze()
		expect(results.violations).toEqual([])

		// Leave the row clean — decline the request so later tests and
		// future runs can reuse the running vacation.
		const row = await managerRow(mgr, ownerId, vacation.id)
		await api(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${vacation.id}/cancel-request/decline`, {
				data: { expectedUpdatedAt: row.updatedAt },
			})
	})

	test('manager decline keeps the absence approved and clears the request', async ({ browser }) => {
		const role = ownerRole()
		const ownerId = process.env[`NC_${role}_USER`]
		const mgr = await browser.newPage()
		const emp = await browser.newPage()

		await login(mgr, credsFromEnv('MANAGER'))
		await mgr.goto(APP + '/manager')
		const vacation = await runningVacation(mgr, ownerId)

		await login(emp, credsFromEnv(role))
		await emp.goto(APP + '/absences')
		const fresh = await ownerAbsence(emp, vacation.id)
		await api(emp, 'POST', `${APP}/api/absences/${vacation.id}/cancel-request`, {
			data: { expectedUpdatedAt: fresh.updatedAt, reason: 'decline me' },
		})

		const row = await managerRow(mgr, ownerId, vacation.id)
		const dec = await api(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${vacation.id}/cancel-request/decline`, {
				data: { expectedUpdatedAt: row.updatedAt, comment: 'we need you' },
			})
		expect(dec.absence.status).toBe('approved')
		expect(dec.absence.cancelRequested).toBe(false)
	})

	test('manager direct cancel: reason_required, revision_stale, cancelled; ended → already_ended', async ({ browser }) => {
		const role = ownerRole()
		const ownerId = process.env[`NC_${role}_USER`]
		const mgr = await browser.newPage()

		await login(mgr, credsFromEnv('MANAGER'))
		await mgr.goto(APP + '/manager')

		// reason_required first — before any state check.
		const running = await runningVacation(mgr, ownerId)
		const noReason = await apiAllowFailure(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${running.id}/cancel`, {
				data: { expectedUpdatedAt: running.updatedAt },
			})
		expect(noReason.status).toBe(400)
		expect(noReason.json.error_code).toBe('reason_required')

		// revision_stale on a bogus token.
		const stale = await apiAllowFailure(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${running.id}/cancel`, {
				data: { expectedUpdatedAt: '2000-01-01T00:00:00+00:00', reason: 'ops' },
			})
		expect(stale.status).toBe(409)
		expect(stale.json.error_code).toBe('revision_stale')

		// Happy path: running approved → cancelled.
		const ok = await api(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${running.id}/cancel`, {
				data: { expectedUpdatedAt: running.updatedAt, reason: 'Operational needs' },
			})
		expect(ok.absence.status).toBe('cancelled')

		// already_ended: a past absence is payroll history.
		const ended = await seedEndedVacation(mgr, ownerId)
		const past = await apiAllowFailure(mgr, 'POST',
			`${APP}/api/manager/employee-absences/${ended.id}/cancel`, {
				data: { expectedUpdatedAt: ended.updatedAt, reason: 'retro' },
			})
		expect(past.status).toBe(422)
		expect(past.json.error_code).toBe('already_ended')
	})
})
